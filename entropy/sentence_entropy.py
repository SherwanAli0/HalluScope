"""Stage 3 - Sentence-level entropy (faithful replication of Eq. 2).

Reads Stage 2 outputs, splits each completion into sentences with spaCy
(as stated in the paper: "responses generated by the LLM were split into
sentences using SpaCy"), assigns generated tokens to sentences via their
character spans, and computes per-sentence entropy as the MEAN of token
entropies - the paper's Eq. 2:

    H(Sen_j) = (1 / N_j) * sum_k H(y_k | c_k)

Token-to-sentence assignment rule (the paper does not specify one - our
documented choice):
  * a token belongs to the sentence its span overlaps most;
  * zero-width tokens (pending UTF-8 bytes) belong to the sentence containing
    their position;
  * special tokens (EOS etc.) are excluded entirely;
  * tokens overlapping NO sentence (pure inter-sentence whitespace, e.g. a
    lone "\n" between list items) are excluded from sentence averages - the
    paper's Eq. 2 sums over tokens "within a sentence".

Output: outputs/<alias>/<dataset>.jsonl, one line per prompt:
  {"id", "dataset", "sentences": [
     {"idx", "text", "start", "end", "n_tokens",
      "mean_entropy", "token_entropies", "mean_logprob"}]}

Usage:
  py -3.11 entropy/sentence_entropy.py --alias smoke
"""

import argparse
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
GEN_DIR = REPO / "generation" / "outputs"
OUT_DIR = HERE / "outputs"


def overlap(a_start, a_end, b_start, b_end):
    return max(0, min(a_end, b_end) - max(a_start, b_start))


def check_record(rec):
    """Validate one Stage-2 record against PIPELINE_CONTRACT section 2.

    Stage 2 may have run on another machine (Colab zip / Drive), so reject
    malformed input loudly instead of silently mis-assigning tokens: spans
    must index into `completion`, be ordered and non-overlapping, and every
    entropy must be finite and non-negative.
    """
    rid = rec.get("id", "?")
    for key in ("id", "dataset", "completion", "tokens"):
        if key not in rec:
            raise ValueError(f"{rid}: missing field {key!r}")
    n = len(rec["completion"])
    prev_end = 0
    for i, tok in enumerate(rec["tokens"]):
        for key in ("entropy", "span", "special", "logprob"):
            if key not in tok:
                raise ValueError(f"{rid}: token {i} missing field {key!r}")
        s, e = tok["span"]
        if not (0 <= s <= e <= n):
            raise ValueError(f"{rid}: token {i} span {[s, e]} outside completion "
                             f"of length {n}")
        if s < prev_end:
            raise ValueError(f"{rid}: token {i} span {[s, e]} overlaps or precedes "
                             f"the previous token (ends at {prev_end})")
        prev_end = e
        ent = tok["entropy"]
        if not (isinstance(ent, (int, float)) and math.isfinite(ent) and ent >= -1e-6):
            raise ValueError(f"{rid}: token {i} entropy {ent!r} is not finite "
                             "and >= 0 (fp16 overflow? wrong logits axis?)")


def assign_tokens(sent_spans, tokens):
    """Map each kept token index to a sentence index (or None)."""
    assignment = []
    for tok in tokens:
        if tok["special"]:
            assignment.append(None)
            continue
        s, e = tok["span"]
        if s == e:  # zero-width: pending byte token - locate by position
            hit = None
            for j, (ss, se) in enumerate(sent_spans):
                if ss <= s < se:
                    hit = j
                    break
            assignment.append(hit)
            continue
        best, best_ov = None, 0
        for j, (ss, se) in enumerate(sent_spans):
            ov = overlap(s, e, ss, se)
            if ov > best_ov:
                best, best_ov = j, ov
        assignment.append(best)  # None when no overlap (inter-sentence ws)
    return assignment


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--alias", required=True)
    ap.add_argument("--gen-dir", default=str(GEN_DIR))
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    ap.add_argument("--spacy-model", default="en_core_web_sm")
    args = ap.parse_args()

    import spacy  # imported here so the pure helpers above are testable without spaCy

    nlp = spacy.load(args.spacy_model, exclude=["ner", "lemmatizer"])

    in_dir = Path(args.gen_dir) / args.alias
    out_dir = Path(args.out_dir) / args.alias
    out_dir.mkdir(parents=True, exist_ok=True)

    files = sorted(in_dir.glob("*.jsonl"))
    assert files, f"no generation outputs found under {in_dir}"

    stats = {"tokens": 0, "kept": 0, "dropped_special": 0, "dropped_ws": 0}
    for f in files:
        out_path = out_dir / f.name
        n_rec = 0
        with open(f, encoding="utf-8") as fin, \
             open(out_path, "w", encoding="utf-8") as fout:
            for line in fin:
                rec = json.loads(line)
                check_record(rec)
                text = rec["completion"]
                doc = nlp(text)
                sent_spans = [(s.start_char, s.end_char) for s in doc.sents]
                sent_texts = [s.text for s in doc.sents]

                assignment = assign_tokens(sent_spans, rec["tokens"])

                per_sent = [[] for _ in sent_spans]
                per_sent_lp = [[] for _ in sent_spans]
                for tok, j in zip(rec["tokens"], assignment):
                    stats["tokens"] += 1
                    if tok["special"]:
                        stats["dropped_special"] += 1
                        continue
                    if j is None:
                        stats["dropped_ws"] += 1
                        continue
                    stats["kept"] += 1
                    per_sent[j].append(tok["entropy"])
                    per_sent_lp[j].append(tok["logprob"])

                sentences = []
                for j, (span, stext) in enumerate(zip(sent_spans, sent_texts)):
                    ents = per_sent[j]
                    if not ents:  # sentence got no tokens (shouldn't happen)
                        continue
                    sentences.append({
                        "idx": j,
                        "text": stext,
                        "start": span[0],
                        "end": span[1],
                        "n_tokens": len(ents),
                        "mean_entropy": sum(ents) / len(ents),
                        "token_entropies": ents,
                        "mean_logprob": sum(per_sent_lp[j]) / len(ents),
                    })

                fout.write(json.dumps({
                    "id": rec["id"], "dataset": rec["dataset"],
                    "sentences": sentences,
                }, ensure_ascii=False) + "\n")
                n_rec += 1
        print(f"[ ok ] {f.name}: {n_rec} records -> {out_path}")

    print(f"[stats] tokens={stats['tokens']} kept={stats['kept']} "
          f"special={stats['dropped_special']} inter-sentence ws={stats['dropped_ws']}")


if __name__ == "__main__":
    main()
